import pandas as pd
import streamlit as st

import common as C
from fakenews.transformer_models import REGISTRY

P = C.cfg().get("project", {})
st.title("About & limitations")
st.subheader("Datasets")
st.markdown("""
| Dataset | What it is | Licence / use |
|---|---|---|
| Synthetic (this repo) | Template-generated English/Hinglish/Hindi items for building and demonstrating the pipeline. **Not** evidence of model quality. | Generated by the project; never publish as real posts |
| LIAR (Wang, 2017) | ~12.8k PolitiFact statements, US political English. Binary mapping: true/mostly-true → real, false/pants-fire → fake. | Research use; cite the paper |
| Your dataset | Your cleaned fake/real collection | Your licence; kept in `data/raw/`, never committed |
""")
st.subheader("Models")
st.dataframe(pd.DataFrame([{"short name": k, "Hugging Face": f"https://huggingface.co/{v['hf']}", "size": v["size"],
                            "languages": v["languages"], "why": v["why"]} for k, v in REGISTRY.items()]),
             hide_index=True, width="stretch",
             column_config={"Hugging Face": st.column_config.LinkColumn()})
st.markdown("Statistical: BoW + Naive Bayes, BoW + Logistic Regression, TF-IDF + Logistic Regression, TF-IDF + Linear "
            "SVM (calibrated), TF-IDF character 3-5-grams + Logistic Regression (scikit-learn).")
st.subheader("Limitations")
st.markdown("""
- A text classifier judges **how a text is written and what it resembles**, not whether the claim is true. A true but
  sensational post can be called fake; a calm, well-written lie can be called real.
- Synthetic scores are near the ceiling set by label noise because templates are learnable; held-out-template
  results (Shortcut audit) show how much is memorisation.
- Random splits overestimate real-world performance; prefer time- or source-based splits on real data.
- LIAR is US political English and does not represent Indian content.
- Language detection without a language column is a heuristic.
""")
st.subheader("Ethics")
st.markdown("No real people are named in the synthetic data. Predictions must never be presented as verified facts. "
            "LLM-suggested labels are not ground truth; a person must confirm them against evidence.")
st.subheader("How to cite / team")
st.markdown(f"**{P.get('title')}** - {P.get('team')} (guide: {P.get('guide')}), {P.get('institution')}. "
            "Code: this repository; tag the release you used for the reported numbers.")
